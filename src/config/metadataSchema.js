export const FIELD_BY_ID = Object.fromEntries(
  METADATA_FIELDS.map((field) => [field.id, field]),
);

export function getDefaultValues() {
  return Object.fromEntries(METADATA_FIELDS.map((field) => [field.id, '']));
}

export function getFieldsForTab(tab) {
  return METADATA_FIELDS.filter((field) => field.tab === tab);
}

export function isFieldSupported(field, format) {
  return !field?.unsupportedIn?.includes(format);
}

export function getFormatLabel(format) {
  return (
    {
      jpeg: 'JPEG',
      png: 'PNG',
      webp: 'WebP',
      tiff: 'TIFF',
      heic: 'HEIC',
      avif: 'AVIF',
    }[format] || String(format || 'image').toUpperCase()
  );
}

